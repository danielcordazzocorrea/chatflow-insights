DROP POLICY IF EXISTS "Users read own campaigns" ON public.campanhas;
CREATE POLICY "Users read own campaigns"
  ON public.campanhas FOR SELECT TO authenticated
  USING (created_by = (SELECT auth.uid()));

DROP POLICY IF EXISTS "Users create own campaigns" ON public.campanhas;
CREATE POLICY "Users create own campaigns"
  ON public.campanhas FOR INSERT TO authenticated
  WITH CHECK (created_by = (SELECT auth.uid()));

DROP POLICY IF EXISTS "Users update own campaigns" ON public.campanhas;
CREATE POLICY "Users update own campaigns"
  ON public.campanhas FOR UPDATE TO authenticated
  USING (created_by = (SELECT auth.uid()))
  WITH CHECK (created_by = (SELECT auth.uid()));

DROP POLICY IF EXISTS "Users delete own campaigns" ON public.campanhas;
CREATE POLICY "Users delete own campaigns"
  ON public.campanhas FOR DELETE TO authenticated
  USING (created_by = (SELECT auth.uid()));

DROP POLICY IF EXISTS "Users read contacts from own campaigns" ON public.envio_em_massa;
CREATE POLICY "Users read contacts from own campaigns"
  ON public.envio_em_massa FOR SELECT TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.campanhas c
      WHERE c.id = envio_em_massa.campanha_id
        AND c.created_by = (SELECT auth.uid())
    )
  );

